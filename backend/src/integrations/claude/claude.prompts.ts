// 6. Message Generation User Prompt Builder (CONS-011: XML tags)
// ---------------------------------------------------------------------------

/**
 * Build the user prompt for message generation with proper XML tagging.
 */
export function buildMessageGenerationUserPrompt(params: {
  prospectData: Record<string, unknown>;
  sequenceNumber: 1 | 2 | 3;
  previousMessages?: Array<{ direction: 'outbound'; text: string; sentAt: string }>;
  agentPromptForStep?: string;
  profileAnalysis?: Record<string, unknown>;
  isWarm?: boolean;
  hasPriorConversation?: boolean;
  conversationSummary?: string;
}): string {
  const {
    prospectData,
    sequenceNumber,
    previousMessages = [],
    agentPromptForStep = '',
    profileAnalysis,
    isWarm = false,
    hasPriorConversation = false,
    conversationSummary = '',
  } = params;

  const stepLabel = sequenceNumber === 1
    ? isWarm ? 'Primo contatto warm' : 'Messaggio introduttivo'
    : sequenceNumber === 2
    ? isWarm ? 'Follow-up warm #1' : 'Follow-up #1'
    : isWarm ? 'Follow-up warm #2' : 'Follow-up #2';

  let prompt = `## Tipo di messaggio: ${stepLabel} (sequenza ${sequenceNumber}/3)

## Dati del prospect
<prospect_data>
${JSON.stringify(prospectData, null, 2)}
</prospect_data>
`;

  if (profileAnalysis) {
    prompt += `
## Analisi del profilo
${JSON.stringify(profileAnalysis, null, 2)}
`;
  }

  if (previousMessages.length > 0) {
    prompt += `
## Messaggi precedenti inviati
${previousMessages.map((m, i) => `[${i + 1}] (${m.sentAt}): ${m.text}`).join('\n')}
`;
  }

  if (isWarm) {
    prompt += `
## Contesto rete calda
- Connessione esistente: sì
- Conversazione precedente: ${hasPriorConversation ? 'sì' : 'no'}
${conversationSummary ? `- Riassunto conversazione: ${conversationSummary}` : ''}
`;
  }

  if (agentPromptForStep) {
    prompt += `
## Istruzioni specifiche per questo step
${agentPromptForStep}
`;
  }

  prompt += `
Genera il messaggio adesso.`;

  return prompt;
}

