// 7. Identity Builder User Prompt Builder
// ---------------------------------------------------------------------------

/**
 * Build the user prompt for identity building from uploaded documents.
 */
export function buildIdentityBuilderUserPrompt(params: {
  documentTexts: Array<{ filename: string; content: string }>;
  agentContext: {
    name?: string;
    role?: string;
    company?: string;
    targetDescription?: string;
  };
}): string {
  const { documentTexts, agentContext } = params;

  let prompt = `Costruisci l'identità digitale per un agente di outreach LinkedIn basandoti sui seguenti documenti.

## Contesto agente fornito dall'utente
- Nome: ${agentContext.name ?? 'Non specificato'}
- Ruolo: ${agentContext.role ?? 'Non specificato'}
- Azienda: ${agentContext.company ?? 'Non specificata'}
- Target descritto: ${agentContext.targetDescription ?? 'Non specificato'}

## Documenti caricati (${documentTexts.length} file)
`;

  for (const doc of documentTexts) {
    prompt += `
### File: ${doc.filename}
---
${doc.content}
---
`;
  }

  prompt += `
Analizza tutti i documenti e costruisci l'identità completa nel formato JSON specificato.`;

  return prompt;
}
