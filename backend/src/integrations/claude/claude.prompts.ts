/**
 * backend/src/integrations/claude/claude.prompts.ts
 *
 * All system-prompt templates used by the LinkedIn Multi-Agent Outreach Platform.
 *
 * Security (CONS-011): Profile and prospect data is placed inside <prospect_data> XML tags
 * and Claude is instructed to treat it as untrusted input to mitigate prompt injection.
 *
 * Each exported function accepts an Identity (or identity-related context) and returns the
 * fully rendered prompt string ready to be passed to ClaudeClient.
 *
 * Identity shape used across prompts:
 * {
 *   name: string                      — human name of the agent identity
 *   role: string                      — professional title / role
 *   company: string                   — company name
 *   value_proposition: string         — one-sentence value prop
 *   tone: string                      — e.g. "professionale ma amichevole"
 *   language: string                  — ISO 639-1, e.g. "it"
 *   fullContextPrompt: string         — full narrative context generated by identity builder
 * }
 */

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface IdentityContext {
  name: string;
  role: string;
  company: string;
  valueProposition: string;
  tone: string;
  language: string;
  fullContextPrompt: string;
}

export interface MessagingConstraints {
  maxMessageLength: number;
  tone: string;
  language: string;
  coldIntroPrompt?: string;
  coldFollowup1Prompt?: string;
  coldFollowup2Prompt?: string;
  warmIntroPrompt?: string;
  warmFollowup1Prompt?: string;
  warmFollowup2Prompt?: string;
}

